#!/usr/bin/env python3
"""
Generate simulation/models/field_env: what surrounds the rice in the X450 world
(do not edit the output by hand; scripts/setup.sh runs this).

  - bunds (bờ ruộng): earthen ridges ~0.25 m high, 0.5 m wide, on the 4 paddy edges
  - West road (đường lộ dọc) along the West bank, North road (home is on it)
  - small dirt paths outside the East and South banks
  - irrigation canal (mương) west of the West road

Geometry comes from tools/mission/field_site.py (survey frame: origin = NW paddy corner,
u east of the West bank, v north along it). Visual only: no collisions, so the
drone takes off from home on the road exactly as before.

Usage:  python3 tools/mission/gen_field_env.py
"""
import math
import shutil
from pathlib import Path

from field_site import CORNER_NW, YAW, paddy_corners_uv

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "simulation" / "models" / "field_env"

MAT = {   # ambient, diffuse, specular
    "bund":  ((0.30, 0.32, 0.20), (0.42, 0.45, 0.26), (0.05, 0.05, 0.05)),
    "road":  ((0.42, 0.38, 0.30), (0.62, 0.56, 0.45), (0.08, 0.08, 0.08)),
    "path":  ((0.38, 0.35, 0.27), (0.55, 0.50, 0.40), (0.05, 0.05, 0.05)),
    "water": ((0.06, 0.10, 0.09), (0.12, 0.20, 0.18), (0.70, 0.75, 0.75)),
}


def strip(name, p1, p2, width, height, z0, mat):
    """Box visual from p1 to p2 (survey frame), centred on the segment."""
    (u1, v1), (u2, v2) = p1, p2
    length = math.hypot(u2 - u1, v2 - v1)
    yaw = math.atan2(v2 - v1, u2 - u1)
    amb, dif, spe = MAT[mat]
    def f(c):
        return " ".join(f"{x:.2f}" for x in c) + " 1"
    return f"""      <visual name="{name}">
        <pose>{(u1 + u2) / 2:.3f} {(v1 + v2) / 2:.3f} {z0 + height / 2:.3f} 0 0 {yaw:.5f}</pose>
        <cast_shadows>false</cast_shadows>
        <geometry><box><size>{length:.3f} {width:.3f} {height:.3f}</size></box></geometry>
        <material><ambient>{f(amb)}</ambient><diffuse>{f(dif)}</diffuse><specular>{f(spe)}</specular></material>
      </visual>"""


def offset(p1, p2, d):
    """Shift segment p1-p2 by d metres to its left (outside, the paddy is clockwise)."""
    (u1, v1), (u2, v2) = p1, p2
    L = math.hypot(u2 - u1, v2 - v1)
    nu, nv = -(v2 - v1) / L * d, (u2 - u1) / L * d
    return (u1 + nu, v1 + nv), (u2 + nu, v2 + nv)


def extend(p1, p2, a, b):
    """Lengthen segment by a metres before p1 and b metres after p2."""
    (u1, v1), (u2, v2) = p1, p2
    L = math.hypot(u2 - u1, v2 - v1)
    du, dv = (u2 - u1) / L, (v2 - v1) / L
    return (u1 - du * a, v1 - dv * a), (u2 + du * b, v2 + dv * b)


def main():
    nw, ne, se, sw = paddy_corners_uv()
    vis = []
    # bunds on the 4 edges
    for name, a, b in [("bund_north", nw, ne), ("bund_east", ne, se), ("bund_south", se, sw), ("bund_west", sw, nw)]:
        vis.append(strip(name, *extend(a, b, 0.25, 0.25), 0.5, 0.25, 0.0, "bund"))
    # West road (3.4 m) along the West bank, North road (6.6 m, home is on it)
    vis.append(strip("road_west", *extend(*offset(sw, nw, 2.0), 6.0, 2.0), 3.4, 0.05, 0.0, "road"))
    n1, n2 = extend(*offset(nw, ne, 3.6), 9.0, 12.0)
    vis.append(strip("road_north", n1, n2, 6.6, 0.05, 0.0, "road"))
    # small paths outside the East and South banks
    vis.append(strip("path_east", *extend(*offset(ne, se, 1.3), 0.0, 1.0), 1.6, 0.04, 0.0, "path"))
    vis.append(strip("path_south", *extend(*offset(se, sw, 1.3), 1.0, 3.7), 1.6, 0.04, 0.0, "path"))
    # canal west of the West road
    vis.append(strip("canal", *extend(*offset(sw, nw, 6.0), 6.0, 2.0), 4.5, 0.02, 0.0, "water"))

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    (OUT / "model.config").write_text("""<?xml version="1.0"?>
<model>
  <name>field_env</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>GENERATED by tools/mission/gen_field_env.py - bunds, roads, canal around the paddy</description>
</model>
""")
    (OUT / "model.sdf").write_text(f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/mission/gen_field_env.py - do not edit by hand, re-run the script.
     Model origin = NW paddy corner, x = east of the West bank, y = north along it. -->
<sdf version="1.9">
  <model name="field_env">
    <static>true</static>
    <pose>{CORNER_NW[0]:.3f} {CORNER_NW[1]:.3f} 0.005 0 0 {YAW:.5f}</pose>
    <link name="link">
{chr(10).join(vis)}
    </link>
  </model>
</sdf>
""")
    print(f"field_env -> {OUT}  ({len(vis)} visuals)")


if __name__ == "__main__":
    main()
